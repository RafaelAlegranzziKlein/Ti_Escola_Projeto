    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (txtID.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Selecione um chamado primeiro!");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
                null,
                "Deseja excluir o Equipamento" + txtPatrimonio_tag.getText() + " ? ",
                "Exclusão",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm == JOptionPane.YES_OPTION) {

            int id_equipamento = Integer.parseInt(txtID.getText().trim());

            String msg = controller.deletar(id_equipamento);
            JOptionPane.showMessageDialog(null, msg);
            listarTabela();

        } else {
            JOptionPane.showMessageDialog(null, "Operação cancelada!");
        }    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (txtID.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Selecione um Equipamento primeiro!");
            return;
        }

        int id_equipamento = Integer.parseInt(txtID.getText().trim());

        String msg = controller.atualizar(
                id_equipamento,
                txtPatrimonio_tag.getText(),
                txtSala.getText()
        );

        JOptionPane.showMessageDialog(null, msg);
        listarTabela();

    }//GEN-LAST:event_btnEditarActionPerformed

    private void tblEquipamentoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblEquipamentoMouseClicked
        int linha = tblEquipamento.getSelectedRow();
        txtID.setText(tblEquipamento.getValueAt(linha, 0).toString());
        txtPatrimonio_tag.setText(tblEquipamento.getValueAt(linha, 1).toString());
        txtSala.setText(tblEquipamento.getValueAt(linha, 2).toString());    }//GEN-LAST:event_tblEquipamentoMouseClicked

