    public void listarTabela() {
        DefaultTableModel model = (DefaultTableModel) tblEquipamento.getModel();
        model.setRowCount(0);

        java.util.List<br.ulbra.model.Equipamento> lista = controller.listar();

        if (lista != null) {
            for (br.ulbra.model.Equipamento e : lista) {
                model.addRow(new Object[]{
                    e.getId_equipamento(),
                    e.getTag_patrimonio(),
                    e.getSala()
                });
            }
        } else {
            JOptionPane.showMessageDialog(null, "Nenhum chamado encontrado!");
        }
    }

